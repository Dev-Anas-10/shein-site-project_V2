#!/usr/bin/env bash
set -Eeuo pipefail

if [[ "${EUID}" -ne 0 ]]; then
  echo "Run this script with sudo: sudo bash scripts/deploy-ec2.sh" >&2
  exit 1
fi

SOURCE_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
APP_DIR="/opt/shein-concierge"
APP_USER="sheinapp"
DB_NAME="shein_concierge"
DB_USER="shein_app"
SERVICE_NAME="shein-concierge"
NGINX_SITE="/etc/nginx/sites-available/${SERVICE_NAME}"

ensure_build_swap() {
  local memory_kb swap_total_kb available_kb swap_file="/swapfile-shein-concierge"

  memory_kb="$(awk '/^MemTotal:/ { print $2 }' /proc/meminfo)"
  swap_total_kb="$(awk 'NR > 1 { total += $3 } END { print total + 0 }' /proc/swaps)"

  if (( memory_kb >= 2097152 || swap_total_kb >= 2097152 )); then
    return 0
  fi

  if [[ ! -e "${swap_file}" ]]; then
    available_kb="$(df -Pk / | awk 'NR == 2 { print $4 }')"
    if (( available_kb < 2359296 )); then
      echo "Less than 2.25 GiB is free on /; cannot safely create build swap." >&2
      exit 1
    fi

    fallocate -l 2G "${swap_file}"
    chmod 0600 "${swap_file}"
    mkswap "${swap_file}" >/dev/null
  fi

  if ! awk -v path="${swap_file}" '$1 == path { found = 1 } END { exit !found }' /proc/swaps; then
    swapon "${swap_file}"
  fi
  if ! grep -qF "${swap_file} none swap sw 0 0" /etc/fstab; then
    printf '%s\n' "${swap_file} none swap sw 0 0" >> /etc/fstab
  fi

  echo "Enabled a 2 GiB swap file to support the production build on this low-memory instance."
}

read -r -p "EC2 public IPv4 address (or domain name): " APP_HOST
# Accept a bare host or pasted URL, and remove accidental spaces.
APP_HOST="${APP_HOST#"${APP_HOST%%[![:space:]]*}"}"
APP_HOST="${APP_HOST%"${APP_HOST##*[![:space:]]}"}"
case "${APP_HOST,,}" in
  http://*) APP_HOST="${APP_HOST:7}" ;;
  https://*) APP_HOST="${APP_HOST:8}" ;;
esac
APP_HOST="${APP_HOST%%/*}"
if [[ "${APP_HOST}" =~ ^[0-9.]+$ ]]; then
  IFS='.' read -r -a IP_OCTETS <<< "${APP_HOST}"
  if [[ "${#IP_OCTETS[@]}" -ne 4 ]]; then
    echo "Enter a valid EC2 public IPv4 address or a domain name." >&2
    exit 1
  fi
  for octet in "${IP_OCTETS[@]}"; do
    if [[ ! "${octet}" =~ ^[0-9]{1,3}$ ]] || ((10#${octet} > 255)); then
      echo "Enter a valid EC2 public IPv4 address or a domain name." >&2
      exit 1
    fi
  done
elif [[ ! "${APP_HOST}" =~ ^([A-Za-z0-9]([A-Za-z0-9-]{0,61}[A-Za-z0-9])?\.)*[A-Za-z0-9]([A-Za-z0-9-]{0,61}[A-Za-z0-9])?$ ]]; then
  echo "Enter a valid EC2 public IPv4 address or a domain name, optionally prefixed with http:// or https://." >&2
  exit 1
fi
echo "Using host: ${APP_HOST}"
read -r -p "Google OAuth Web Client ID (leave blank to disable Google sign-in): " GOOGLE_CLIENT_ID

EXISTING_PGPASSWORD=""
EXISTING_SESSION_SECRET=""
if [[ -f "${APP_DIR}/.env.production" ]]; then
  # This file is generated by this script and contains only shell-safe values.
  # shellcheck disable=SC1091
  source "${APP_DIR}/.env.production"
  EXISTING_PGPASSWORD="${PGPASSWORD:-}"
  EXISTING_SESSION_SECRET="${SESSION_SECRET:-}"
fi
DB_PASSWORD="${EXISTING_PGPASSWORD:-$(openssl rand -hex 32)}"
SESSION_SECRET="${EXISTING_SESSION_SECRET:-$(openssl rand -hex 64)}"

systemctl stop "${SERVICE_NAME}" 2>/dev/null || true

export DEBIAN_FRONTEND=noninteractive
apt-get update
apt-get install -y ca-certificates curl gnupg git rsync openssl nginx postgresql postgresql-contrib

install -d -m 0755 /etc/apt/keyrings
curl -fsSL https://deb.nodesource.com/gpgkey/nodesource-repo.gpg.key \
  | gpg --dearmor --yes -o /etc/apt/keyrings/nodesource.gpg
chmod 0644 /etc/apt/keyrings/nodesource.gpg
echo "deb [signed-by=/etc/apt/keyrings/nodesource.gpg] https://deb.nodesource.com/node_22.x nodistro main" \
  > /etc/apt/sources.list.d/nodesource.list
apt-get update
apt-get install -y nodejs
ensure_build_swap

if ! id -u "${APP_USER}" >/dev/null 2>&1; then
  useradd --system --home-dir "${APP_DIR}" --create-home --shell /usr/sbin/nologin "${APP_USER}"
fi
install -d -o "${APP_USER}" -g "${APP_USER}" -m 0750 "${APP_DIR}"
if [[ "${SOURCE_DIR}" != "${APP_DIR}" ]]; then
  rsync -a --delete \
    --exclude='.git/' \
    --exclude='node_modules/' \
    --exclude='.next/' \
    --exclude='.env*' \
    "${SOURCE_DIR}/" "${APP_DIR}/"
fi
chown -R "${APP_USER}:${APP_USER}" "${APP_DIR}"

sudo -u postgres psql -v ON_ERROR_STOP=1 \
  --set=db_name="${DB_NAME}" \
  --set=db_user="${DB_USER}" \
  --set=db_password="${DB_PASSWORD}" <<'SQL'
SELECT format('CREATE ROLE %I LOGIN PASSWORD %L', :'db_user', :'db_password')
WHERE NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = :'db_user')
\gexec
SELECT format('ALTER ROLE %I WITH LOGIN PASSWORD %L', :'db_user', :'db_password')
\gexec
SELECT format('CREATE DATABASE %I OWNER %I', :'db_name', :'db_user')
WHERE NOT EXISTS (SELECT 1 FROM pg_database WHERE datname = :'db_name')
\gexec
SQL

sudo -u postgres psql -v ON_ERROR_STOP=1 -c "ALTER SYSTEM SET listen_addresses = '127.0.0.1'"
systemctl enable postgresql
systemctl restart postgresql

cat > "${APP_DIR}/.env.production" <<EOF
NODE_ENV=production
PORT=3000
PGHOST=127.0.0.1
PGPORT=5432
PGDATABASE=${DB_NAME}
PGUSER=${DB_USER}
PGPASSWORD=${DB_PASSWORD}
PGPOOL_MAX=10
SESSION_SECRET=${SESSION_SECRET}
SESSION_COOKIE_SECURE=false
NEXT_PUBLIC_GOOGLE_CLIENT_ID=${GOOGLE_CLIENT_ID}
EOF
# Next.js reads .env.production during the build, which runs as APP_USER.
# Keep secrets private from other users while allowing the service account to read them.
chown "root:${APP_USER}" "${APP_DIR}/.env.production"
chmod 0640 "${APP_DIR}/.env.production"

set -a
# shellcheck disable=SC1091
source "${APP_DIR}/.env.production"
set +a

sudo -u "${APP_USER}" bash -lc "cd '${APP_DIR}' && npm install"
sudo -u "${APP_USER}" --preserve-env=PGHOST,PGPORT,PGDATABASE,PGUSER,PGPASSWORD,PGPOOL_MAX,NODE_ENV,SESSION_SECRET,NEXT_PUBLIC_GOOGLE_CLIENT_ID \
  bash -lc "cd '${APP_DIR}' && npm run db:bootstrap"

read -r -p "Migrate users and orders from the current Supabase project now? [y/N] " MIGRATE_LEGACY
if [[ "${MIGRATE_LEGACY}" =~ ^[Yy]$ ]]; then
  read -r -p "Old Supabase project URL: " LEGACY_SUPABASE_URL
  read -r -s -p "Old Supabase service_role key: " LEGACY_SUPABASE_SERVICE_ROLE_KEY
  echo
  if [[ -z "${LEGACY_SUPABASE_URL}" || -z "${LEGACY_SUPABASE_SERVICE_ROLE_KEY}" ]]; then
    echo "Both the old Supabase URL and service_role key are required for migration." >&2
    exit 1
  fi
  export LEGACY_SUPABASE_URL LEGACY_SUPABASE_SERVICE_ROLE_KEY
  sudo -u "${APP_USER}" --preserve-env=PGHOST,PGPORT,PGDATABASE,PGUSER,PGPASSWORD,PGPOOL_MAX,LEGACY_SUPABASE_URL,LEGACY_SUPABASE_SERVICE_ROLE_KEY \
    bash -lc "cd '${APP_DIR}' && npm run db:migrate-supabase"
  unset LEGACY_SUPABASE_SERVICE_ROLE_KEY
fi

sudo -u "${APP_USER}" --preserve-env=PGHOST,PGPORT,PGDATABASE,PGUSER,PGPASSWORD,PGPOOL_MAX,NODE_ENV,SESSION_SECRET,NEXT_PUBLIC_GOOGLE_CLIENT_ID \
  bash -lc "cd '${APP_DIR}' && npm run build"

read -r -p "Create or update an admin account now? [Y/n] " CREATE_ADMIN
if [[ ! "${CREATE_ADMIN}" =~ ^[Nn]$ ]]; then
  read -r -p "Admin name: " ADMIN_NAME
  read -r -p "Admin email: " ADMIN_EMAIL
  export ADMIN_NAME ADMIN_EMAIL
  sudo -u "${APP_USER}" --preserve-env=PGHOST,PGPORT,PGDATABASE,PGUSER,PGPASSWORD,PGPOOL_MAX,ADMIN_NAME,ADMIN_EMAIL \
    bash -lc "cd '${APP_DIR}' && npm run admin:create"
fi

cat > "/etc/systemd/system/${SERVICE_NAME}.service" <<EOF
[Unit]
Description=SHEIN Concierge Next.js application
After=network.target postgresql.service
Wants=postgresql.service

[Service]
Type=simple
User=${APP_USER}
Group=${APP_USER}
WorkingDirectory=${APP_DIR}
EnvironmentFile=${APP_DIR}/.env.production
Environment=NODE_ENV=production
Environment=NEXT_TELEMETRY_DISABLED=1
ExecStart=/usr/bin/npm run start -- --hostname 127.0.0.1 --port 3000
Restart=on-failure
RestartSec=5
TimeoutStopSec=30
NoNewPrivileges=true
PrivateTmp=true

[Install]
WantedBy=multi-user.target
EOF

sed "s/__SERVER_NAME__/${APP_HOST}/g" "${APP_DIR}/deploy/nginx/shein-concierge.conf" \
  > "${NGINX_SITE}"
ln -sfn "${NGINX_SITE}" "/etc/nginx/sites-enabled/${SERVICE_NAME}"
rm -f /etc/nginx/sites-enabled/default
nginx -t
systemctl enable nginx
systemctl reload nginx || systemctl start nginx

systemctl daemon-reload
systemctl enable --now "${SERVICE_NAME}"

for attempt in $(seq 1 30); do
  if curl --fail --silent http://127.0.0.1:3000/ >/dev/null; then
    break
  fi
  sleep 2
done
if ! curl --fail --silent http://127.0.0.1:3000/ >/dev/null; then
  systemctl --no-pager --full status "${SERVICE_NAME}" || true
  journalctl -u "${SERVICE_NAME}" -n 80 --no-pager || true
  echo "The app did not become healthy. Check the service logs above." >&2
  exit 1
fi

echo
echo "Deployment is ready: http://${APP_HOST}"
echo "The app is bound to 127.0.0.1:3000; PostgreSQL is bound to 127.0.0.1:5432."
echo "In the EC2 security group allow inbound TCP 22 and 80. Do not expose port 5432."
echo "Service logs: journalctl -u ${SERVICE_NAME} -f"
